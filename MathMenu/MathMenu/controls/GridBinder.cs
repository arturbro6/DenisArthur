using System;
using System.Data;
using System.Windows.Controls;

namespace MathMenu.controls
{
    /// <summary>
    /// Привязка таблицы DataTable к DataGrid: последний столбец растягивается
    /// на свободное место, чтобы справа не оставалось пустой области заголовка.
    /// </summary>
    public static class GridBinder
    {
        public static void Bind(DataGrid grid, DataTable table)
        {
            grid.ItemsSource = table.DefaultView;
            grid.AutoGeneratedColumns -= Grid_AutoGeneratedColumns;
            grid.AutoGeneratedColumns += Grid_AutoGeneratedColumns;
            StretchLastColumn(grid);
        }

        private static void Grid_AutoGeneratedColumns(object sender, EventArgs e)
        {
            StretchLastColumn((DataGrid)sender);
        }

        private static void StretchLastColumn(DataGrid grid)
        {
            if (grid.Columns.Count > 0)
            {
                grid.Columns[grid.Columns.Count - 1].Width =
                    new DataGridLength(1.0, DataGridLengthUnitType.Star);
            }
        }
    }
}
